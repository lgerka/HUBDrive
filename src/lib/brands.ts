/** Марка по адресу страницы. */
export function brandBySlug(slug: string): BrandInfo | null {
    return BRAND_INFO[slug.toLowerCase()] ?? null;
}

/** Адрес страницы по названию марки из базы. */
export function slugForBrand(brand: string): string {
    const found = Object.values(BRAND_INFO).find(
        b => b.brand.toLowerCase() === brand.trim().toLowerCase()
    );
    if (found) return found.slug;
    // Марка, которой ещё нет в списке: чистим до латиницы и цифр, иначе
    // «Lynk & Co» превратится в адрес, по которому страницы не существует
    return brand
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
}

